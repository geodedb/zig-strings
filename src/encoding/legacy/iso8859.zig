//! ISO-8859 Character Encodings
//!
//! Provides encoding/decoding for the ISO-8859 family:
//! - ISO-8859-1 (Latin-1): Western European
//! - ISO-8859-2 (Latin-2): Central European
//! - ISO-8859-3 (Latin-3): South European
//! - ISO-8859-4 (Latin-4): North European
//! - ISO-8859-5: Cyrillic
//! - ISO-8859-6: Arabic
//! - ISO-8859-7: Greek
//! - ISO-8859-8: Hebrew
//! - ISO-8859-9 (Latin-5): Turkish
//! - ISO-8859-10 (Latin-6): Nordic
//! - ISO-8859-11: Thai
//! - ISO-8859-13 (Latin-7): Baltic Rim
//! - ISO-8859-14 (Latin-8): Celtic
//! - ISO-8859-15 (Latin-9): Western European with Euro
//! - ISO-8859-16 (Latin-10): South-Eastern European
//!
//! Usage:
//! ```zig
//! // Decode ISO-8859-1 to UTF-8
//! const utf8 = try ISO8859.Latin1.decode(allocator, iso_bytes);
//! defer allocator.free(utf8);
//!
//! // Encode UTF-8 to ISO-8859-15
//! const iso = try ISO8859.Latin9.encode(allocator, utf8_string);
//! defer allocator.free(iso);
//! ```

const std = @import("std");
const legacy_errors = @import("legacy_encoding_errors");

/// Encoding/decoding errors
pub const ISO8859Error = legacy_errors.LegacyEncodingError;

/// ISO-8859 encoding variants
pub const ISO8859 = enum {
    Latin1, // ISO-8859-1: Western European
    Latin2, // ISO-8859-2: Central European
    Latin3, // ISO-8859-3: South European
    Latin4, // ISO-8859-4: North European
    Cyrillic, // ISO-8859-5
    Arabic, // ISO-8859-6
    Greek, // ISO-8859-7
    Hebrew, // ISO-8859-8
    Latin5, // ISO-8859-9: Turkish
    Latin6, // ISO-8859-10: Nordic
    Thai, // ISO-8859-11
    Latin7, // ISO-8859-13: Baltic Rim
    Latin8, // ISO-8859-14: Celtic
    Latin9, // ISO-8859-15: Western European + Euro
    Latin10, // ISO-8859-16: South-Eastern European

    /// Decode ISO-8859 bytes to UTF-8
    pub fn decode(self: ISO8859, allocator: std.mem.Allocator, input: []const u8) ![]u8 {
        var result: std.ArrayListUnmanaged(u8) = .{};
        errdefer result.deinit(allocator);

        for (input) |byte| {
            const cp = self.byteToCodepoint(byte);

            var buf: [4]u8 = undefined;
            const len = std.unicode.utf8Encode(cp, &buf) catch {
                try result.appendSlice(allocator, "\xEF\xBF\xBD");
                continue;
            };
            try result.appendSlice(allocator, buf[0..len]);
        }

        return result.toOwnedSlice(allocator);
    }

    /// Encode UTF-8 to ISO-8859 bytes
    pub fn encode(self: ISO8859, allocator: std.mem.Allocator, input: []const u8) ![]u8 {
        var result: std.ArrayListUnmanaged(u8) = .{};
        errdefer result.deinit(allocator);

        var iter = std.unicode.Utf8Iterator{ .bytes = input, .i = 0 };
        while (iter.nextCodepoint()) |cp| {
            if (self.codepointToByte(cp)) |byte| {
                try result.append(allocator, byte);
            } else {
                try result.append(allocator, '?');
            }
        }

        return result.toOwnedSlice(allocator);
    }

    /// Convert a single byte to Unicode codepoint
    pub fn byteToCodepoint(self: ISO8859, byte: u8) u21 {
        if (byte < 128) return byte;

        return switch (self) {
            .Latin1 => byte, // ISO-8859-1 maps directly to Unicode
            .Latin2 => iso8859_2_table[byte - 128],
            .Latin3 => iso8859_3_table[byte - 128],
            .Latin4 => iso8859_4_table[byte - 128],
            .Cyrillic => iso8859_5_table[byte - 128],
            .Arabic => iso8859_6_table[byte - 128],
            .Greek => iso8859_7_table[byte - 128],
            .Hebrew => iso8859_8_table[byte - 128],
            .Latin5 => iso8859_9_table[byte - 128],
            .Latin6 => iso8859_10_table[byte - 128],
            .Thai => iso8859_11_table[byte - 128],
            .Latin7 => iso8859_13_table[byte - 128],
            .Latin8 => iso8859_14_table[byte - 128],
            .Latin9 => iso8859_15_table[byte - 128],
            .Latin10 => iso8859_16_table[byte - 128],
        };
    }

    /// Convert Unicode codepoint to byte (if possible)
    pub fn codepointToByte(self: ISO8859, cp: u21) ?u8 {
        if (cp < 128) return @intCast(cp);

        // ISO-8859-1 is special - direct mapping for 0x80-0xFF
        if (self == .Latin1) {
            if (cp <= 0xFF) return @intCast(cp);
            return null;
        }

        const table = switch (self) {
            .Latin1 => unreachable,
            .Latin2 => &iso8859_2_table,
            .Latin3 => &iso8859_3_table,
            .Latin4 => &iso8859_4_table,
            .Cyrillic => &iso8859_5_table,
            .Arabic => &iso8859_6_table,
            .Greek => &iso8859_7_table,
            .Hebrew => &iso8859_8_table,
            .Latin5 => &iso8859_9_table,
            .Latin6 => &iso8859_10_table,
            .Thai => &iso8859_11_table,
            .Latin7 => &iso8859_13_table,
            .Latin8 => &iso8859_14_table,
            .Latin9 => &iso8859_15_table,
            .Latin10 => &iso8859_16_table,
        };

        for (table, 0..) |table_cp, i| {
            if (table_cp == cp) {
                return @intCast(i + 128);
            }
        }
        return null;
    }

    /// Check if codepoint is encodable
    pub fn isEncodable(self: ISO8859, cp: u21) bool {
        return self.codepointToByte(cp) != null;
    }
};

