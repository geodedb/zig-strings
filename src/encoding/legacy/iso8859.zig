test "ISO-8859-1 decode" {
    const testing = std.testing;

    // ISO-8859-1 maps directly to Unicode 0x00-0xFF
    const input = [_]u8{ 0xE9, 0xE8, 0xE0 }; // é è à
    const result = try ISO8859.Latin1.decode(testing.allocator, &input);
    defer testing.allocator.free(result);

    try testing.expectEqualStrings("\xc3\xa9\xc3\xa8\xc3\xa0", result);
}

test "ISO-8859-1 encode" {
    const testing = std.testing;

    const result = try ISO8859.Latin1.encode(testing.allocator, "\xc3\xa9"); // é
    defer testing.allocator.free(result);

    try testing.expectEqual(@as(u8, 0xE9), result[0]);
}

test "ISO-8859-15 Euro sign" {
    const testing = std.testing;

    // ISO-8859-15 has Euro at 0xA4
    const input = [_]u8{0xA4};
    const result = try ISO8859.Latin9.decode(testing.allocator, &input);
    defer testing.allocator.free(result);

    try testing.expectEqualStrings("\xe2\x82\xac", result); // €
}

test "ISO-8859-5 Cyrillic" {
    const testing = std.testing;

    // Cyrillic А is at 0xB0
    const input = [_]u8{0xB0};
    const result = try ISO8859.Cyrillic.decode(testing.allocator, &input);
    defer testing.allocator.free(result);

    try testing.expectEqualStrings("\xd0\x90", result); // А
