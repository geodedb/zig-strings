test "ASCII passthrough" {
    const testing = std.testing;

    const result = try ISO8859.Latin1.decode(testing.allocator, "Hello");
    defer testing.allocator.free(result);

    try testing.expectEqualStrings("Hello", result);
}

test "isEncodable" {
    const testing = std.testing;

    // ASCII always encodable
    try testing.expect(ISO8859.Latin1.isEncodable('A'));

    // Latin-1 range
    try testing.expect(ISO8859.Latin1.isEncodable(0xE9)); // é

    // Euro not in Latin-1, but in Latin-9
    try testing.expect(!ISO8859.Latin1.isEncodable(0x20AC));
    try testing.expect(ISO8859.Latin9.isEncodable(0x20AC));
}
