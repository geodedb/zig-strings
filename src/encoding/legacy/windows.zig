test "CP1252 decode" {
    const testing = std.testing;

    // ASCII passthrough
    const result1 = try CodePage.CP1252.decode(testing.allocator, "Hello");
    defer testing.allocator.free(result1);
    try testing.expectEqualStrings("Hello", result1);

    // High bytes
    const input = [_]u8{ 0x80, 0x93, 0x94 }; // Euro, left quote, right quote
    const result2 = try CodePage.CP1252.decode(testing.allocator, &input);
    defer testing.allocator.free(result2);
    try testing.expectEqualStrings("\xe2\x82\xac\xe2\x80\x9c\xe2\x80\x9d", result2);
}

test "CP1252 encode" {
    const testing = std.testing;

    // ASCII passthrough
    const result1 = try CodePage.CP1252.encode(testing.allocator, "Hello");
    defer testing.allocator.free(result1);
    try testing.expectEqualStrings("Hello", result1);

    // Euro sign
    const result2 = try CodePage.CP1252.encode(testing.allocator, "\xe2\x82\xac");
    defer testing.allocator.free(result2);
    try testing.expectEqual(@as(u8, 0x80), result2[0]);
}

test "CP1251 Cyrillic" {
    const testing = std.testing;

    // Encode some Cyrillic letters
    const input = [_]u8{ 0xC0, 0xC1, 0xC2 }; // А Б В
    const result = try CodePage.CP1251.decode(testing.allocator, &input);
    defer testing.allocator.free(result);

    // Should decode to UTF-8 Cyrillic
    try testing.expectEqualStrings("\xd0\x90\xd0\x91\xd0\x92", result);
}

