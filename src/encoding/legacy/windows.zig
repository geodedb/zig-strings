//! Windows Code Pages
//!
//! Provides encoding/decoding for Windows code pages:
//! - CP1250: Central European (Polish, Czech, Hungarian, etc.)
//! - CP1251: Cyrillic (Russian, Ukrainian, Bulgarian, etc.)
//! - CP1252: Western European (default Windows encoding)
//! - CP1253: Greek
//! - CP1254: Turkish
//! - CP1255: Hebrew
//! - CP1256: Arabic
//! - CP1257: Baltic (Estonian, Latvian, Lithuanian)
//! - CP1258: Vietnamese
//! - CP437: Original IBM PC
//! - CP850: DOS Latin-1
//!
//! Usage:
//! ```zig
//! // Decode Windows-1252 to UTF-8
//! const utf8 = try CodePage.CP1252.decode(allocator, windows_bytes);
//! defer allocator.free(utf8);
//!
//! // Encode UTF-8 to Windows-1252
//! const cp1252 = try CodePage.CP1252.encode(allocator, utf8_string);
//! defer allocator.free(cp1252);
//! ```

const std = @import("std");
const legacy_errors = @import("legacy_encoding_errors");

/// Encoding/decoding errors
pub const CodePageError = legacy_errors.LegacyEncodingError;

/// Windows Code Page identifier
pub const CodePage = enum {
    CP1250, // Central European
    CP1251, // Cyrillic
    CP1252, // Western European
    CP1253, // Greek
    CP1254, // Turkish
    CP1255, // Hebrew
    CP1256, // Arabic
    CP1257, // Baltic
    CP1258, // Vietnamese
    CP437, // DOS US
    CP850, // DOS Latin-1

    /// Decode code page bytes to UTF-8
    pub fn decode(self: CodePage, allocator: std.mem.Allocator, input: []const u8) ![]u8 {
        const table = self.getDecodeTable();
        const low_table = self.getLowByteTable();
        var result: std.ArrayListUnmanaged(u8) = .{};
        errdefer result.deinit(allocator);

        for (input) |byte| {
            var cp: u21 = undefined;
            if (byte < 32 and low_table != null) {
                // Use low-byte table for control characters (CP437/CP850)
                cp = low_table.?[byte];
            } else if (byte < 128) {
                cp = @as(u21, byte);
            } else {
                cp = table[byte - 128];
            }

            if (cp == 0xFFFD or cp == 0) {
                // Undefined - use replacement character
                try result.appendSlice(allocator, "\xEF\xBF\xBD");
            } else {
                var buf: [4]u8 = undefined;
                const len = std.unicode.utf8Encode(cp, &buf) catch {
                    try result.appendSlice(allocator, "\xEF\xBF\xBD");
                    continue;
                };
                try result.appendSlice(allocator, buf[0..len]);
            }
        }

        return result.toOwnedSlice(allocator);
    }

    /// Encode UTF-8 to code page bytes
    pub fn encode(self: CodePage, allocator: std.mem.Allocator, input: []const u8) ![]u8 {
        var result: std.ArrayListUnmanaged(u8) = .{};
        errdefer result.deinit(allocator);

        var iter = std.unicode.Utf8Iterator{ .bytes = input, .i = 0 };
        while (iter.nextCodepoint()) |cp| {
            if (cp < 128) {
                try result.append(allocator, @intCast(cp));
            } else if (self.encodeCodepoint(cp)) |byte| {
                try result.append(allocator, byte);
            } else {
                // Unmappable - use ?
                try result.append(allocator, '?');
            }
        }

        return result.toOwnedSlice(allocator);
    }

    /// Encode a single codepoint to a byte (if possible)
    pub fn encodeCodepoint(self: CodePage, cp: u21) ?u8 {
        if (cp < 128) return @intCast(cp);

        const table = self.getDecodeTable();
        for (table, 0..) |table_cp, i| {
            if (table_cp == cp) {
                return @intCast(i + 128);
            }
        }
        return null;
    }

    /// Check if codepoint is encodable
    pub fn isEncodable(self: CodePage, cp: u21) bool {
        return cp < 128 or self.encodeCodepoint(cp) != null;
    }

    /// Get the decode table for this code page
    fn getDecodeTable(self: CodePage) *const [128]u21 {
        return switch (self) {
            .CP1250 => &cp1250_table,
            .CP1251 => &cp1251_table,
            .CP1252 => &cp1252_table,
            .CP1253 => &cp1253_table,
            .CP1254 => &cp1254_table,
            .CP1255 => &cp1255_table,
            .CP1256 => &cp1256_table,
            .CP1257 => &cp1257_table,
            .CP1258 => &cp1258_table,
            .CP437 => &cp437_table,
            .CP850 => &cp850_table,
        };
    }

    /// Get the low-byte table for code pages with graphical control chars (CP437/CP850)
    fn getLowByteTable(self: CodePage) ?*const [32]u21 {
        return switch (self) {
            .CP437 => &cp437_low_table,
            .CP850 => &cp437_low_table, // CP850 uses same low-byte mapping as CP437
            else => null,
        };
    }
};

