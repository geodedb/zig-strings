test "CP437 low-byte graphical characters" {
    const testing = std.testing;

    // Test smiley face characters (0x01, 0x02)
    const input1 = [_]u8{ 0x01, 0x02 }; // ☺ ☻
    const result1 = try CodePage.CP437.decode(testing.allocator, &input1);
    defer testing.allocator.free(result1);
    try testing.expectEqualStrings("\xe2\x98\xba\xe2\x98\xbb", result1); // ☺☻

    // Test card suit characters (0x03-0x06)
    const input2 = [_]u8{ 0x03, 0x04, 0x05, 0x06 }; // ♥♦♣♠
    const result2 = try CodePage.CP437.decode(testing.allocator, &input2);
    defer testing.allocator.free(result2);
    try testing.expectEqualStrings("\xe2\x99\xa5\xe2\x99\xa6\xe2\x99\xa3\xe2\x99\xa0", result2); // ♥♦♣♠

    // Test arrows (0x18-0x1B)
    const input3 = [_]u8{ 0x18, 0x19, 0x1A, 0x1B }; // ↑↓→←
    const result3 = try CodePage.CP437.decode(testing.allocator, &input3);
    defer testing.allocator.free(result3);
    try testing.expectEqualStrings("\xe2\x86\x91\xe2\x86\x93\xe2\x86\x92\xe2\x86\x90", result3); // ↑↓→←
}

